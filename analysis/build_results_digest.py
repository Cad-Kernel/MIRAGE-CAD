# --- geometry (delegated to the committed aggregator) ---------------------
h("0.10 Best-of-N geometry  →  paper `tab:geometry` and `tab:ablation_selection`", 3)
print("Seeded random 100-part subset, the same parts for both modalities. Selection is "
      "Chamfer + 0.1*bbox error. Delegated to the committed aggregator rather than "
      "reimplemented here, so the selection logic cannot drift.\n")
_agg = REPO / "src/scratch/aggregate_geometry_nbest.py"
for m in ("step", "point"):
    rows_f = SCRATCH / f"geometry_nbest_random100_{m}" / "geometry_nbest_rows.jsonl"
    if not (_agg.exists() and rows_f.exists()):
        print(f"- {LABEL[m]}: rows or aggregator missing, skipped")
        continue
    import subprocess
    r = subprocess.run([sys.executable, str(_agg), str(rows_f)],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    txt = r.stdout or ""
    print(f"**{LABEL[m]}**\n")
    print("| N | Build | Median CD | Median F@1% | Paired median CD |")
    print("|---|---|---|---|---|")
    cur, acc = None, {}
    for line in txt.splitlines():
        line = line.strip()
        mm = __import__("re").match(r"--- N=(\d+) \(n_samples=\d+\) ---", line)
        if mm:
            cur = mm.group(1)
            acc.setdefault(cur, {})
        elif cur:
            for key, pat in (("build", r"Build:\s+\d+/\d+ = ([\d.]+)%"),
                             ("cd", r"Median CD:\s+([\d.]+)"),
                             ("f1", r"Median F@1%:\s+([\d.]+)%")):
                g = __import__("re").match(pat, line)
                if g:
                    acc[cur][key] = g.group(1)
        g = __import__("re").match(r"N=\s*(\d+): paired-subset median CD = ([\d.]+)", line)
        if g:
            acc.setdefault(g.group(1), {})["paired"] = g.group(2)
    for n in ("1", "3", "5", "10"):
        d = acc.get(n, {})
        print(f"| {n} | {d.get('build','--')}% | {d.get('cd','--')} "
              f"| {d.get('f1','--')}% | {d.get('paired','--')} |")
    print()
print("The all-scored median CD worsens with N because a rising Build dilutes the "
      "scored pool; the paired subset (STEP n=63, point n=42) is the reliable read. "
      "Median F@1% declines throughout, so the two geometry metrics disagree about "
      "whether selection helps.\n")
src("scratch/geometry_nbest_random100_step/geometry_nbest_rows.jsonl",
    "scratch/geometry_nbest_random100_point/geometry_nbest_rows.jsonl",
    "src/scratch/aggregate_geometry_nbest.py",
    "src/training_25k/20_rerun_geometry_nbest_random100.sh")

