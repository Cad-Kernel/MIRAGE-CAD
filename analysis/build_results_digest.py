"""Generate the verified results digest for docs/MIRAGE-CAD_experiment_results.md.

Every number this emits is READ FROM A FILE, never typed by hand, and each block prints
the file it came from. That is the whole point: the digest is meant for cross-checking
against paper/main.tex, so a transcription error here would defeat it.

    python src/scratch/build_results_digest.py > digest.md

Only fast JSON reads are done inline (seconds). Numbers that need a heavy pass over the
corpus or the raw rows are not recomputed here; instead the digest names the script that
produces them, so the chain stays auditable either way.
"""
