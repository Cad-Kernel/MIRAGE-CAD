LABEL = {"step": "STEP / B-Rep", "point": "Point cloud", "text": "Text", "image": "Image"}
Z = 1.959963985


def wilson(k: int, n: int) -> tuple[float, float]:
    p = k / n
    d = 1 + Z * Z / n
    c = (p + Z * Z / (2 * n)) / d
    h = Z * math.sqrt(p * (1 - p) / n + Z * Z / (4 * n * n)) / d
    return 100 * max(0.0, c - h), 100 * min(1.0, c + h)


def jload(p: Path):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None


def rel(p: Path) -> str:
    try:
        return str(p.relative_to(REPO)).replace("\\", "/")
    except ValueError:
        s = str(p).replace("\\", "/")
        return s.replace(str(WSL).replace("\\", "/"), "<wsl>/src")


def exec_row(d: Path):
    """(rows, syntax%, build%, export%, build_count) from an execution_summary.json."""
    s = jload(d / "execution_summary.json")
    if not s:
        return None
    n = s.get("rows")
    if not n:
        return None
    return (n, 100 * s.get("syntax_ok_rate", float("nan")),
            100 * s.get("build_ok_rate", float("nan")),
            100 * s.get("step_export_ok_rate", float("nan")),
            s.get("build_ok_count"))


def h(title, level=3):
    print(f"\n{'#' * level} {title}\n")


def src(*paths):
    print("\n**Source files**:")
    for p in paths:
        print(f"- `{p}`")
    print()


